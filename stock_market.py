import pandas as pd
import numpy as np


# ==========================================
# 1. LOAD DATA
# ==========================================

df = pd.read_csv("stock_data.csv")

# Remove extra spaces from column names
df.columns = df.columns.str.strip()

# Convert Date column into date format
df["Date"] = pd.to_datetime(df["Date"])


# ==========================================
# 2. CLEAN DATA
# ==========================================

df = df.drop_duplicates()
df = df.dropna()

# Sort data
df = df.sort_values(["Company", "Date"])


print("==========================================")
print("     STOCK MARKET DATA ANALYSIS SYSTEM")
print("==========================================")

print("\nData loaded successfully.")

print("\nAvailable Columns:")
print(df.columns.tolist())

print("\nTotal Records:", len(df))


# ==========================================
# 3. DISPLAY DATA
# ==========================================

print("\n==========================================")
print("             STOCK MARKET DATA")
print("==========================================")

print(df.to_string(index=False))


# ==========================================
# 4. AVAILABLE COMPANIES
# ==========================================

companies = df["Company"].unique()

print("\n==========================================")
print("           AVAILABLE COMPANIES")
print("==========================================")

for i in range(len(companies)):
    print(i + 1, ".", companies[i])


# ==========================================
# 5. SELECT COMPANY
# ==========================================

choice = int(input("\nEnter company number: "))

company = companies[choice - 1]

stock = df[df["Company"] == company].copy()

stock = stock.sort_values("Date")


print("\nSelected Company:", company)


# ==========================================
# 6. BASIC STATISTICS
# ==========================================

average_open = stock["Open"].mean()
average_high = stock["High"].mean()
average_low = stock["Low"].mean()
average_close = stock["Close"].mean()

highest_price = stock["High"].max()
lowest_price = stock["Low"].min()

average_volume = stock["Volume"].mean()

highest_volume = stock["Volume"].max()
lowest_volume = stock["Volume"].min()


print("\n==========================================")
print("             BASIC STATISTICS")
print("==========================================")

print("Company              :", company)
print("Average Open Price   :", round(average_open, 2))
print("Average High Price   :", round(average_high, 2))
print("Average Low Price    :", round(average_low, 2))
print("Average Close Price  :", round(average_close, 2))

print("Highest Price        :", highest_price)
print("Lowest Price         :", lowest_price)

print("Average Volume       :", round(average_volume, 2))
print("Highest Volume       :", highest_volume)
print("Lowest Volume        :", lowest_volume)


# ==========================================
# 7. DAILY RETURN
# ==========================================

stock["Daily_Return"] = stock["Close"].pct_change() * 100


print("\n==========================================")
print("              DAILY RETURNS")
print("==========================================")

print(
    stock[
        ["Date", "Close", "Daily_Return"]
    ].to_string(index=False)
)


# ==========================================
# 8. TOTAL RETURN
# ==========================================

starting_price = stock["Close"].iloc[0]

ending_price = stock["Close"].iloc[-1]

total_return = (
    (ending_price - starting_price)
    / starting_price
) * 100


print("\n==========================================")
print("             RETURN ANALYSIS")
print("==========================================")

print("Starting Price :", starting_price)
print("Ending Price   :", ending_price)

print(
    "Total Return   :",
    round(total_return, 2),
    "%"
)


# ==========================================
# 9. POSITIVE AND NEGATIVE DAYS
# ==========================================

positive_days = (
    stock["Daily_Return"] > 0
).sum()

negative_days = (
    stock["Daily_Return"] < 0
).sum()

no_change_days = (
    stock["Daily_Return"] == 0
).sum()


print("\n==========================================")
print("          DAILY PERFORMANCE")
print("==========================================")

print("Positive Days  :", positive_days)
print("Negative Days  :", negative_days)
print("No Change Days :", no_change_days)


# ==========================================
# 10. VOLATILITY
# ==========================================

returns = stock["Daily_Return"].dropna()

volatility = np.std(returns)


print("\n==========================================")
print("          VOLATILITY ANALYSIS")
print("==========================================")

print(
    "Historical Volatility :",
    round(volatility, 2),
    "%"
)


# ==========================================
# 11. TREND ANALYSIS
# ==========================================

if ending_price > starting_price:

    trend = "UPWARD"

elif ending_price < starting_price:

    trend = "DOWNWARD"

else:

    trend = "STABLE"


print("\n==========================================")
print("             TREND ANALYSIS")
print("==========================================")

print("Overall Trend :", trend)


# ==========================================
# 12. RISK ANALYSIS
# ==========================================

if volatility < 2:

    risk = "LOW"

elif volatility < 4:

    risk = "MEDIUM"

else:

    risk = "HIGH"


print("\n==========================================")
print("              RISK ANALYSIS")
print("==========================================")

print("Volatility :", round(volatility, 2), "%")
print("Risk Level :", risk)


# ==========================================
# 13. COMPANY COMPARISON
# ==========================================

print("\n==========================================")
print("             COMPANY COMPARISON")
print("==========================================")


for company_name in companies:

    company_data = df[
        df["Company"] == company_name
    ].copy()

    company_data = company_data.sort_values("Date")

    first_price = company_data["Close"].iloc[0]

    last_price = company_data["Close"].iloc[-1]

    company_return = (
        (last_price - first_price)
        / first_price
    ) * 100

    company_returns = (
        company_data["Close"]
        .pct_change()
        .dropna()
        * 100
    )

    company_volatility = np.std(
        company_returns
    )

    print("\nCompany :", company_name)

    print(
        "Starting Price :",
        first_price
    )

    print(
        "Ending Price   :",
        last_price
    )

    print(
        "Total Return   :",
        round(company_return, 2),
        "%"
    )

    print(
        "Volatility     :",
        round(company_volatility, 2),
        "%"
    )


# ==========================================
# 14. FINAL REPORT
# ==========================================

print("\n\n")
print("==============================================")
print("          STOCK MARKET ANALYSIS REPORT")
print("==============================================")

print("Company             :", company)

print(
    "Analysis Period     :",
    stock["Date"].min().date(),
    "to",
    stock["Date"].max().date()
)

print("----------------------------------------------")

print(
    "Average Open Price  :",
    round(average_open, 2)
)

print(
    "Average High Price  :",
    round(average_high, 2)
)

print(
    "Average Low Price   :",
    round(average_low, 2)
)

print(
    "Average Close Price :",
    round(average_close, 2)
)

print(
    "Highest Price       :",
    highest_price
)

print(
    "Lowest Price        :",
    lowest_price
)

print(
    "Average Volume      :",
    round(average_volume, 2)
)

print("----------------------------------------------")

print(
    "Starting Price      :",
    starting_price
)

print(
    "Ending Price        :",
    ending_price
)

print(
    "Total Return        :",
    round(total_return, 2),
    "%"
)

print(
    "Positive Days       :",
    positive_days
)

print(
    "Negative Days       :",
    negative_days
)

print(
    "No Change Days      :",
    no_change_days
)

print("----------------------------------------------")

print(
    "Volatility          :",
    round(volatility, 2),
    "%"
)

print(
    "Overall Trend       :",
    trend
)

print(
    "Risk Level          :",
    risk
)

print("----------------------------------------------")

print(
    "Note: Risk level is based on historical"
)

print(
    "volatility and does not predict future"
)

print(
    "stock performance."
)

print("==============================================")

